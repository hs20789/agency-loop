def _digest(value: str) -> str:
    return hashlib.sha256(value.encode()).hexdigest()


def text(value: str) -> dict:
    return {"type": "text", "text": value}


def think(value: str) -> dict:
    return {"type": "thinking", "thinking": value, "signature": "EqQBCkYIBxgC" + _digest(value)[:48]}


def slash(name: str) -> str:
    return f"<command-name>/{name}</command-name>\n<command-message>{name}</command-message>\n<command-args></command-args>"


def line_of(source: str, needle: str) -> int:
    return next(n for n, line in enumerate(source.splitlines(), 1) if needle in line)


class Session:
    """Builds the lines of one JSONL file in Claude Code's record shapes."""

    def __init__(self, key: str) -> None:
        self.key = key
        self.lines: list[str] = []
        self.count = 0  # records, drives uuids and timestamps
        self.messages = 0  # assistant API messages
        self.tools = 0
        self.pending: list[str] = []  # tool_use ids waiting for their tool_result
        self.parent: str | None = None
        self.session_id = self._uuid("session")

    def _uuid(self, label: str) -> str:
        return str(uuid.UUID(hex=_digest(f"{self.key}/{label}")[:32], version=4))

    def _tick(self) -> str:
        self.count += 1
        t = START + timedelta(seconds=9 * self.count, milliseconds=137 * self.count)
        return t.strftime("%Y-%m-%dT%H:%M:%S.") + f"{t.microsecond // 1000:03d}Z"

    def raw(self, line: str) -> None:
        self.lines.append(line)

    def put(self, record: dict) -> None:
        self.raw(json.dumps(record, ensure_ascii=False, separators=(",", ":")))

    def record(self, kind: str, *, sidechain: bool = False, **fields) -> None:
        timestamp = self._tick()
        uid = self._uuid(f"record-{self.count}")
        self.put(
            {
                "parentUuid": self.parent, "isSidechain": sidechain, "userType": "external", "cwd": CWD,
                "sessionId": self.session_id, "version": VERSION, "gitBranch": "main", "type": kind,
                **fields, "uuid": uid, "timestamp": timestamp,
            }
        )
        self.parent = uid

    # Noise records the parser must skip.
    def summary(self, value: str) -> None:
        self.put({"type": "summary", "summary": value, "leafUuid": self.parent})

    def snapshot(self) -> None:
        timestamp = self._tick()
        mid = self._uuid(f"snapshot-{self.count}")
        self.put(
            {
                "type": "file-history-snapshot", "messageId": mid,
                "snapshot": {"messageId": mid, "trackedFileBackups": {}, "timestamp": timestamp},
                "isSnapshotUpdate": False,
            }
        )

    def system(self, content: str) -> None:
        self.record("system", subtype="informational", content=content, isMeta=False, level="info")

    # Conversation records.
    def human(self, content: str | list, *, meta: bool = False, sidechain: bool = False) -> None:
        extra = {"isMeta": True} if meta else {}
        self.record("user", sidechain=sidechain, message={"role": "user", "content": content}, **extra)

    def say(self, *blocks: dict, split: bool = True) -> None:
        """One assistant API message; split=True writes one record per content block, as Claude Code does."""
        self.messages += 1
        n = self.messages
        message = {
            "id": "msg_01" + _digest(f"{self.key}/msg-{n}")[:22], "type": "message", "role": "assistant",
            "model": MODEL, "content": [], "stop_reason": None, "stop_sequence": None,
            "usage": {
                "input_tokens": 4 + n % 7, "cache_creation_input_tokens": 180 * n,
                "cache_read_input_tokens": 11800 + 412 * n, "output_tokens": 96 + 53 * n, "service_tier": "standard",
            },
        }
        request_id = "req_011C" + _digest(f"{self.key}/req-{n}")[:18]
        for group in [[block] for block in blocks] if split else [list(blocks)]:
            self.record("assistant", message={**message, "content": group}, requestId=request_id)

    def use(self, name: str, tool_input: dict) -> dict:
        self.tools += 1
        tool_id = "toolu_01" + _digest(f"{self.key}/tool-{self.tools}")[:22]
        self.pending.append(tool_id)
        return {"type": "tool_use", "id": tool_id, "name": name, "input": tool_input}

    def result(self, output: str, *, extra: dict, is_error: bool = False, as_list: bool = False) -> None:
        block = {
            "tool_use_id": self.pending.pop(0), "type": "tool_result",
            "content": [text(output)] if as_list else output, "is_error": is_error,
        }
        self.record("user", message={"role": "user", "content": [block]}, toolUseResult=extra)

    def write(self, rel: str, content: str, *, before: tuple | list = ()) -> None:
        path = f"{CWD}/{rel}"
        self.say(*before, self.use("Write", {"file_path": path, "content": content}))
        self.result(
            f"File created successfully at: {path}",
            extra={"type": "create", "filePath": path, "content": content, "structuredPatch": []},
        )

    def edit(self, rel: str, old: str, new: str, *, before: tuple | list = (), split: bool = True) -> None:
        path = f"{CWD}/{rel}"
        self.say(*before, self.use("Edit", {"file_path": path, "old_string": old, "new_string": new}), split=split)
        self.result(
            f"The file {path} has been updated.",
            extra={
                "filePath": path, "oldString": old, "newString": new, "structuredPatch": [],
                "userModified": False, "replaceAll": False,
            },
        )

    def bash(self, command: str, stdout: str, *, exit_code: int = 0, before: tuple | list = (), as_list: bool = False) -> None:
        """Claude Code style: a failing command's content starts with "Exit code N"; a passing one has no exit line."""
        self.say(*before, self.use("Bash", {"command": command, "description": "명령 실행"}))
        self.result(
            f"Exit code {exit_code}\n{stdout}" if exit_code else stdout, is_error=bool(exit_code), as_list=as_list,
            extra={"stdout": stdout, "stderr": "", "interrupted": False, "isImage": False},
        )


